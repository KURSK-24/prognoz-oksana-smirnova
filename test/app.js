function skyOfMonth(year, month, sunSign){
  var out = [];
  for (var k=0;k<SKY.events.length;k++){
    var e = SKY.events[k], d = idxToDate(Math.round(e.i*24/SKY.stepH));
    if (d.getUTCFullYear()!==year || d.getUTCMonth()!==month) continue;
    var z = (e.s - sunSign + 12) % 12;
    var mean = SKY_MEAN[e.t][e.p]; if (!mean) continue;
    out.push({day:d.getUTCDate(), ev:SKY_TEXT[e.t](e.p, e.s), zone:ZONE[z], mean:mean, todo:(e.t==="R" ? ZONE_BACK : ZONE_GO)[z]});
  }
  out.sort(function(a,b){ return a.day-b.day; });
  var used = {};
  for (var q=0;q<out.length;q++){
    if (used[out[q].todo]){ var zi = ZONE.indexOf(out[q].zone); out[q].todo = used[ZONE_ALT[zi]] ? ZONE_GO[zi] : ZONE_ALT[zi]; }
    used[out[q].todo] = 1;
  }
  return out;
}

